import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export function generateSeed(text) {
  const names = [...new Map(text.split(/\r?\n/).map(s => s.trim()).filter(Boolean)
    .map(name => [name.toLowerCase(), name])).values()]
  if (names.some(name => name.includes('\0'))) throw new Error('Theme names cannot contain NUL characters.')
  if (!names.length) return '-- No themes to import.\n'
  return '-- Generated by npm run seed. Existing themes and voting data are preserved.\n'
    + 'begin;\ninsert into public.items (name, rating) values\n'
    + names.map(name => `  (E'${name.replaceAll('\\', '\\\\').replaceAll("'", "''")}', 1500)`).join(',\n')
    + '\non conflict do nothing;\ncommit;\n'
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const input = process.argv[2] || 'themes.txt'
  const output = process.argv[3] || 'supabase/seed.sql'
  writeFileSync(output, generateSeed(readFileSync(input, 'utf8')))
  console.log(`Created ${output} from ${input}.`)
}
